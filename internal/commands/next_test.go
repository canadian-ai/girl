const complexGoFunc = `package app

func Route(kind string, n int, flags []bool) int {
	total := 0
	if kind == "a" {
		total++
	} else if kind == "b" {
		total += 2
	} else if kind == "c" {
		total += 3
	}
	for i := 0; i < n; i++ {
		if i%2 == 0 && flags[0] {
			total++
		} else if i%3 == 0 || flags[1] {
			total--
		}
		switch i {
		case 1:
			total += 10
		case 2:
			total += 20
		case 3:
			total += 30
		}
	}
	return total
}
`

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestNext_RanksGroupsAndExcludesNoise(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":                  "module example.com/app\n\ngo 1.25\n",
		"app/route.go":            complexGoFunc,
		"app/simple.go":           "package app\n\nfunc Simple() int { return 1 }\n",
		"app/zz_generated.go":     "// Code generated by tool. DO NOT EDIT.\n\n" + strings.Replace(complexGoFunc, "Route", "Generated", 1),
		"app/testdata/fixture.go": strings.Replace(complexGoFunc, "Route", "Fixture", 1),
		"vendor/dep/dep.go":       strings.Replace(complexGoFunc, "package app", "package dep", 1),
	})

	res, err := buildNext(root, nextOptions{Limit: 5, ExcerptLines: 4})
	if err != nil {
		t.Fatal(err)
	}
	if res.Schema != NextSchema {
		t.Fatalf("schema = %q", res.Schema)
	}
	if len(res.Items) != 1 {
		data, _ := json.MarshalIndent(res, "", "  ")
		t.Fatalf("expected exactly one location (generated, testdata, vendor excluded), got %d:\n%s", len(res.Items), data)
	}
	item := res.Items[0]
	if item.File != "app/route.go" || item.Symbol != "Route" || item.Rank != 1 {
		t.Fatalf("unexpected item: %+v", item)
	}
	if item.ID != "app/route.go#Route" {
		t.Errorf("id = %q", item.ID)
	}
	if !containsString(item.Codes, "go.high-complexity") {
		t.Errorf("codes = %v, want go.high-complexity", item.Codes)
	}
	if item.Recipe == "" || item.Action == "" {
		t.Errorf("item should carry a recipe and action: %+v", item)
	}
	if !strings.Contains(item.Excerpt, "    3  func Route(") {
		t.Errorf("excerpt should be numbered source starting at the function:\n%s", item.Excerpt)
	}
	if !strings.Contains(item.Excerpt, "more lines to line") {
		t.Errorf("excerpt should note truncation:\n%s", item.Excerpt)
	}
	if !containsString(res.Verify, "go test ./...") {
		t.Errorf("verify = %v, want repo-native go test", res.Verify)
	}

	data, _ := json.Marshal(res)
	if strings.Contains(string(data), root) {
		t.Errorf("output leaks absolute path %s", root)
	}
}

func TestNext_LimitAndMinSeverity(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{"go.mod": "module example.com/app\n\ngo 1.25\n"}
	for _, name := range []string{"a", "b", "c", "d"} {
		files["app/"+name+".go"] = strings.Replace(complexGoFunc, "Route", "Route"+strings.ToUpper(name), 1)
	}
	writeTree(t, root, files)

	res, err := buildNext(root, nextOptions{Limit: 2})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Items) != 2 || res.Remaining != 2 {
		t.Fatalf("items=%d remaining=%d, want 2 and 2", len(res.Items), res.Remaining)
	}
	if res.Items[0].Rank != 1 || res.Items[1].Rank != 2 {
		t.Errorf("ranks not sequential: %d, %d", res.Items[0].Rank, res.Items[1].Rank)
	}
	if res.Items[0].Excerpt != "" {
		t.Error("excerpt should be empty when ExcerptLines is 0")
	}

	high, err := buildNext(root, nextOptions{Limit: 10, MinSeverity: "high"})
	if err != nil {
		t.Fatal(err)
	}
	for _, it := range high.Items {
		if it.Severity != "high" {
			t.Errorf("min-severity high returned %s item", it.Severity)
		}
	}
}

func TestNext_TypeScriptFunctions(t *testing.T) {
	root := t.TempDir()
	var body strings.Builder
	body.WriteString("export function parse(input: string, mode: number): number {\n  let n = 0;\n")
	for i := 0; i < 14; i++ {
		body.WriteString("  if (input.length > " + string(rune('0'+i%10)) + " && mode > 1) { n++; }\n")
	}
	body.WriteString("  return n;\n}\n")
	writeTree(t, root, map[string]string{
		"package.json":      `{"name":"app","scripts":{"test":"vitest"}}`,
		"src/parse.ts":      body.String(),
		"src/types.d.ts":    "export declare function parse(input: string): number;\n",
		"src/bundle.min.js": strings.ReplaceAll(strings.ReplaceAll(body.String(), ": string", ""), ": number", ""),
	})
	res, err := buildNext(root, nextOptions{Limit: 5})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Items) != 1 || res.Items[0].File != "src/parse.ts" {
		data, _ := json.MarshalIndent(res, "", "  ")
		t.Fatalf("expected the plain TS function to be reported once:\n%s", data)
	}
	if !containsString(res.Items[0].Codes, "ts.high-complexity") {
		t.Errorf("codes = %v", res.Items[0].Codes)
	}
}

func TestCapabilities_DescribesLiveCommands(t *testing.T) {
	app := &cli.App{Name: "girl", Version: "test", Commands: []*cli.Command{NextCommand(), CheckCommand(), AgentCommand()}}
	caps := BuildCapabilities(app)
	if caps.Schema != CapabilitiesSchema {
		t.Fatalf("schema = %q", caps.Schema)
	}
	byName := map[string]CommandCapability{}
	for _, c := range caps.Commands {
		byName[c.Name] = c
	}
	next, ok := byName["next"]
	if !ok {
		t.Fatal("next command missing")
	}
	var limit *FlagCapability
	for i := range next.Flags {
		if next.Flags[i].Name == "limit" {
			limit = &next.Flags[i]
		}
	}
	if limit == nil || limit.Default != "5" || !limit.Value || len(limit.Aliases) == 0 {
		t.Fatalf("limit flag not described correctly: %+v", limit)
	}
	if len(byName["agent"].Subcommands) == 0 {
		t.Error("agent subcommands missing")
	}
	if len(caps.AgentLoop) == 0 || !strings.HasPrefix(caps.AgentLoop[0].Command, "girl next") {
		t.Errorf("agent loop should start with girl next: %+v", caps.AgentLoop)
	}
}

// Regression: a changed _test.go or generated file used to fall through to
// the TypeScript parser and abort `girl check --changed` / `girl next --changed`.
func TestAnalyzeCheckScope_ChangedSkipsTestsAndGenerated(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":            "module example.com/app\n\ngo 1.25\n",
		"app/route.go":      complexGoFunc,
		"app/route_test.go": "package app\n\nimport \"testing\"\n\nfunc TestRoute(t *testing.T) {}\n",
		"app/zz_gen.go":     "// Code generated by tool. DO NOT EDIT.\n\n" + strings.Replace(complexGoFunc, "Route", "Generated", 1),
		"api/user.pb.go":    strings.Replace(complexGoFunc, "package app", "package api", 1),
	})
	changed := []string{"app/route.go", "app/route_test.go", "app/zz_gen.go", "api/user.pb.go", "README.md"}
	res, err := analyzeCheckScope(root, changed, true)
	if err != nil {
		t.Fatalf("changed-file analysis failed: %v", err)
	}
	if len(res.Files) != 1 {
		t.Fatalf("analyzed %d files, want only app/route.go", len(res.Files))
	}
	for _, d := range res.Diagnostics {
		if !strings.HasSuffix(d.File, "route.go") {
			t.Errorf("unexpected diagnostic in %s", d.File)
		}
	}
}
