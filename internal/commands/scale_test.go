package commands

// Scale tests exercise the full agent-facing pipeline on large repositories.
//
//	go test ./internal/commands -run Scale                    # synthetic, ~1k files
//	GIRL_SCALE=1 go test ./internal/commands -run Scale -v    # 10x synthetic + Go stdlib
//	GIRL_SCALE=1 GIRL_SCALE_CORPUS=/src/vscode:/src/react go test ./internal/commands -run Scale -v
//
// GIRL_SCALE_BUDGET (Go duration, default 3m) bounds each real-corpus run.

import (
	"encoding/json"
	"fmt"
	"go/build"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
	"time"

	"github.com/canadian-ai/girl/internal/planner"
	"github.com/canadian-ai/girl/internal/shared"
	"github.com/canadian-ai/girl/pkg/grp"
)

func scaleEnabled() bool { return os.Getenv("GIRL_SCALE") != "" }

// noiseDirs must never appear in findings: they are dependencies, build
// output, or fixtures, not code an agent should refactor.
var noiseDirs = []string{"vendor/", "node_modules/", "dist/", "testdata/", ".next/"}

type syntheticRepo struct {
	root        string
	handwritten int
	hotspotFile string
	hotspotSym  string
}

// buildSyntheticRepo writes a deterministic mixed Go + TypeScript monorepo.
// One in every seven functions is branch-heavy, one in eleven is long, and a
// single planted hotspot is worse than everything else.
func buildSyntheticRepo(t testing.TB, root string, goFiles, tsFiles int) syntheticRepo {
	t.Helper()
	repo := syntheticRepo{root: root}
	write := func(rel, content string) {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	write("go.mod", "module example.com/mono\n\ngo 1.25\n")
	write("package.json", `{"name":"mono","private":true,"scripts":{"typecheck":"tsc --noEmit","test":"vitest run"}}`)

	for i := 0; i < goFiles; i++ {
		pkg := fmt.Sprintf("svc%02d", i%40)
		write(fmt.Sprintf("services/%s/file%04d.go", pkg, i), syntheticGoFile(pkg, i))
		repo.handwritten++
	}
	for i := 0; i < tsFiles; i++ {
		dir := fmt.Sprintf("apps/web/src/feature%02d", i%40)
		if i%3 == 0 {
			write(fmt.Sprintf("%s/Widget%04d.tsx", dir, i), realTSXFixture(t, i))
		} else {
			write(fmt.Sprintf("%s/logic%04d.ts", dir, i), syntheticTSFile(i))
		}
		repo.handwritten++
	}

	repo.hotspotFile = "services/core/hotspot.go"
	repo.hotspotSym = "Reconcile"
	write(repo.hotspotFile, syntheticHotspot())
	repo.handwritten++

	// Noise: same smells, but none of it is hand-written source.
	noise := syntheticBranchyGo("noise", "Noise", 30)
	for i := 0; i < goFiles/10+1; i++ {
		write(fmt.Sprintf("services/gen/zz_generated_%03d.go", i), "// Code generated by synth. DO NOT EDIT.\n\n"+noise)
		write(fmt.Sprintf("api/v1/msg%03d.pb.go", i), noise)
		write(fmt.Sprintf("vendor/github.com/dep/dep%03d/dep.go", i), noise)
		write(fmt.Sprintf("services/core/testdata/fixture%03d.go", i), noise)
	}
	branchyTS := syntheticTSFile(7)
	for i := 0; i < tsFiles/10+1; i++ {
		write(fmt.Sprintf("node_modules/lib%03d/index.ts", i), branchyTS)
		write(fmt.Sprintf("apps/web/dist/chunk%03d.min.js", i), branchyTS)
		write(fmt.Sprintf("apps/web/src/types/api%03d.d.ts", i), "export declare function api(): void;\n")
		write(fmt.Sprintf("apps/web/src/gen/schema%03d.ts", i), "/* @generated by codegen */\n"+branchyTS)
	}
	return repo
}

func syntheticGoFile(pkg string, i int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\nimport \"strings\"\n\n", pkg)
	for f := 0; f < 4; f++ {
		n := i*4 + f
		switch {
		case n%7 == 0:
			b.WriteString(syntheticBranchyGo("", fmt.Sprintf("Branchy%d", n), 14)[len("package \n\n"):])
		case n%11 == 0:
			fmt.Fprintf(&b, "func Long%d(s string) string {\n", n)
			for l := 0; l < 90; l++ {
				fmt.Fprintf(&b, "\ts = strings.TrimSpace(s + %q)\n", fmt.Sprint(l))
			}
			b.WriteString("\treturn s\n}\n\n")
		default:
			fmt.Fprintf(&b, "func Small%d(s string) string {\n\treturn strings.ToUpper(s)\n}\n\n", n)
		}
	}
	return b.String()
}

func syntheticBranchyGo(pkg, name string, branches int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\nfunc %s(v int) int {\n\tout := 0\n", pkg, name)
	for i := 0; i < branches; i++ {
		fmt.Fprintf(&b, "\tif v > %d && v%%%d == 0 {\n\t\tout += %d\n\t}\n", i, i+2, i)
	}
	b.WriteString("\treturn out\n}\n\n")
	return b.String()
}

func syntheticHotspot() string {
	var b strings.Builder
	b.WriteString("package core\n\nfunc Reconcile(a, b, c, d, e, f int) int {\n\tout := 0\n")
	for i := 0; i < 40; i++ {
		fmt.Fprintf(&b, "\tif a > %d {\n\t\tif b > %d {\n\t\t\tif c > %d {\n\t\t\t\tif d > %d {\n\t\t\t\t\tif e > %d || f > %d {\n\t\t\t\t\t\tout++\n\t\t\t\t\t}\n\t\t\t\t}\n\t\t\t}\n\t\t}\n\t}\n", i, i, i, i, i, i)
	}
	b.WriteString("\treturn out\n}\n")
	return b.String()
}

func syntheticTSFile(i int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "export function small%d(x: number): number {\n  return x * 2;\n}\n\n", i)
	if i%7 == 0 {
		fmt.Fprintf(&b, "export function route%d(kind: string, n: number): number {\n  let out = 0;\n", i)
		for c := 0; c < 14; c++ {
			fmt.Fprintf(&b, "  if (kind === 'k%d' && n > %d) { out += %d; }\n", c, c, c)
		}
		b.WriteString("  return out;\n}\n")
	}
	return b.String()
}

// realTSXFixtures are the real-world and golden React components shipped in
// testdata/; cycling through them keeps the synthetic monorepo's React code
// realistic (hooks, effects, conditionals, repeated JSX) as it scales.
var realTSXFixtures = []string{
	"testdata/real/broker-workspace.tsx",
	"testdata/real/insurance-review-panel.tsx",
	"testdata/golden/react-multi-diag/input/App.tsx",
	"testdata/golden/react-too-many-hooks/input/App.tsx",
	"testdata/golden/grp-react/input/App.tsx",
}

func realTSXFixture(t testing.TB, i int) string {
	t.Helper()
	rel := realTSXFixtures[(i/3)%len(realTSXFixtures)]
	data, err := os.ReadFile(filepath.Join("..", "..", filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("read fixture %s: %v", rel, err)
	}
	return string(data)
}

func scaleFactor() int {
	if scaleEnabled() {
		return 10
	}
	return 1
}

func TestScaleSynthetic(t *testing.T) {
	if testing.Short() {
		t.Skip("scale test skipped in -short mode")
	}
	n := 300 * scaleFactor()
	root := t.TempDir()
	repo := buildSyntheticRepo(t, root, n, n)

	start := time.Now()
	res, err := buildNext(root, nextOptions{Limit: 25, ExcerptLines: 8})
	elapsed := time.Since(start)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("synthetic: %d files, %d diagnostics, %d locations in %s (%.0f files/s, %d workers)",
		res.Summary.Files, res.Summary.Diagnostics, res.Summary.Locations, elapsed.Round(time.Millisecond),
		float64(res.Summary.Files)/elapsed.Seconds(), shared.Workers())

	t.Run("counts only hand-written source", func(t *testing.T) {
		if res.Summary.Files != repo.handwritten {
			t.Fatalf("files scanned = %d, want %d hand-written (generated/vendored/fixture files leaked in or real files dropped)",
				res.Summary.Files, repo.handwritten)
		}
	})

	t.Run("finds planted smells in both languages", func(t *testing.T) {
		all, err := buildNext(root, nextOptions{Limit: 1 << 30})
		if err != nil {
			t.Fatal(err)
		}
		codes := map[string]int{}
		for _, it := range all.Items {
			for _, c := range it.Codes {
				codes[c]++
			}
			for _, noise := range noiseDirs {
				if strings.Contains(it.File, noise) {
					t.Errorf("finding in noise path %s", it.File)
				}
			}
			if strings.Contains(it.File, "generated") || strings.HasSuffix(it.File, ".pb.go") ||
				strings.HasSuffix(it.File, ".d.ts") || strings.Contains(it.File, "/gen/") {
				t.Errorf("finding in generated file %s", it.File)
			}
		}
		// Every 7th Go function is branchy: 4 functions per file.
		wantGoBranchy := 0
		for f := 0; f < n*4; f++ {
			if f%7 == 0 {
				wantGoBranchy++
			}
		}
		if got := codes["go.high-complexity"]; got != wantGoBranchy+1 {
			t.Errorf("go.high-complexity = %d, want %d (+1 hotspot)", got, wantGoBranchy)
		}
		if codes["go.long-function"] == 0 || codes["ts.high-complexity"] == 0 ||
			codes["react.too-many-hooks"] == 0 || codes["react.large-component"] == 0 {
			t.Errorf("missing expected codes: %v", codes)
		}
	})

	t.Run("planted hotspot ranks first", func(t *testing.T) {
		top := res.Items[0]
		if top.File != repo.hotspotFile || top.Symbol != repo.hotspotSym {
			t.Fatalf("rank 1 = %s#%s, want %s#%s", top.File, top.Symbol, repo.hotspotFile, repo.hotspotSym)
		}
		if len(top.Codes) < 2 {
			t.Errorf("hotspot should merge several rules into one item, got %v", top.Codes)
		}
	})

	t.Run("every item is agent-ready", func(t *testing.T) {
		if len(res.Items) != 25 || res.Remaining <= 0 {
			t.Fatalf("limit not honoured: %d items, %d remaining", len(res.Items), res.Remaining)
		}
		for _, it := range res.Items {
			if it.Action == "" || it.Recipe == "" || it.Excerpt == "" || it.Line == 0 || it.EndLine < it.Line {
				t.Errorf("item %s missing action/recipe/excerpt/span: %+v", it.ID, it)
			}
		}
		if len(res.Verify) == 0 {
			t.Error("no verification commands detected for the repo")
		}
	})

	t.Run("output never leaks absolute paths", func(t *testing.T) {
		data, _ := json.Marshal(res)
		if strings.Contains(string(data), root) {
			t.Fatal("JSON output contains the absolute repository path")
		}
	})

	t.Run("deterministic across runs and worker counts", func(t *testing.T) {
		want, _ := json.Marshal(res)
		again, err := buildNext(root, nextOptions{Limit: 25, ExcerptLines: 8})
		if err != nil {
			t.Fatal(err)
		}
		got, _ := json.Marshal(again)
		if string(got) != string(want) {
			t.Fatal("two parallel runs disagree")
		}
		t.Setenv("GIRL_JOBS", "1")
		serial, err := buildNext(root, nextOptions{Limit: 25, ExcerptLines: 8})
		if err != nil {
			t.Fatal(err)
		}
		got, _ = json.Marshal(serial)
		if string(got) != string(want) {
			t.Fatal("serial (GIRL_JOBS=1) and parallel runs disagree")
		}
	})

	t.Run("GRP plan for the whole repo validates", func(t *testing.T) {
		analysis, err := analyzeCheckScope(root, nil, false)
		if err != nil {
			t.Fatal(err)
		}
		plan := planner.NewPlanner().GeneratePlan(planner.PlanRequest{
			Target: shared.DisplayTarget(root), Diagnostics: analysis.Diagnostics, Files: analysis.Files, Lang: "mixed",
		})
		gp := grp.FromIRPlan(plan)
		grp.NormalizePlan(gp)
		gp.ID = canonicalGRPPlanID(plan, "mixed")
		if v := grp.ValidatePlan(gp); !v.Valid {
			t.Fatalf("plan invalid: %+v", v.Errors[:min(5, len(v.Errors))])
		}
		if len(gp.Steps) == 0 {
			t.Fatal("plan has no steps")
		}
	})

	if scaleEnabled() {
		budget := 60 * time.Second
		if elapsed > budget {
			t.Errorf("synthetic analysis took %s, budget %s", elapsed, budget)
		}
	}
}

// TestScaleRealCorpus runs GIRL against real large codebases: the Go standard
// library (always present where Go is installed) plus GIRL_SCALE_CORPUS.
func TestScaleRealCorpus(t *testing.T) {
	if !scaleEnabled() {
		t.Skip("set GIRL_SCALE=1 to run real-corpus scale tests")
	}
	budget := 3 * time.Minute
	if v, err := time.ParseDuration(os.Getenv("GIRL_SCALE_BUDGET")); err == nil {
		budget = v
	}
	corpora := []string{filepath.Join(build.Default.GOROOT, "src")}
	for _, p := range filepath.SplitList(os.Getenv("GIRL_SCALE_CORPUS")) {
		if p != "" {
			corpora = append(corpora, p)
		}
	}

	t.Logf("| corpus | files | diagnostics | locations | time | files/s |")
	t.Logf("|---|---:|---:|---:|---:|---:|")
	for _, corpus := range corpora {
		corpus := corpus
		t.Run(filepath.Base(corpus), func(t *testing.T) {
			if _, err := os.Stat(corpus); err != nil {
				t.Skipf("corpus unavailable: %v", err)
			}
			runtime.GC()
			start := time.Now()
			res, err := buildNext(corpus, nextOptions{Limit: 10, ExcerptLines: 6})
			elapsed := time.Since(start)
			if err != nil {
				t.Fatal(err)
			}
			t.Logf("| %s | %d | %d | %d | %s | %.0f |", filepath.Base(corpus), res.Summary.Files, res.Summary.Diagnostics,
				res.Summary.Locations, elapsed.Round(100*time.Millisecond), float64(res.Summary.Files)/elapsed.Seconds())

			if elapsed > budget {
				t.Errorf("took %s, budget %s", elapsed, budget)
			}
			if res.Summary.Files == 0 || len(res.Items) == 0 {
				t.Fatalf("no files or findings: %+v", res.Summary)
			}
			data, _ := json.Marshal(res)
			if strings.Contains(string(data), corpus) {
				t.Error("output leaks the absolute corpus path")
			}
			for _, it := range res.Items {
				for _, noise := range noiseDirs {
					if strings.Contains("/"+it.File, "/"+noise) {
						t.Errorf("finding in noise path %s", it.File)
					}
				}
				head, err := os.ReadFile(filepath.Join(corpus, filepath.FromSlash(it.File)))
				if err != nil {
					t.Errorf("item file %s not resolvable under corpus: %v", it.File, err)
					continue
				}
				if shared.IsGeneratedSource(head) {
					t.Errorf("finding in generated file %s", it.File)
				}
				if it.Excerpt == "" || it.Action == "" {
					t.Errorf("item %s is not agent-ready", it.ID)
				}
			}
		})
	}
}
